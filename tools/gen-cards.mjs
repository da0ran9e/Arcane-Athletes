// One-time generator: parses GAME_RULES_AND_ASSETS_MASTER.md into
// shared/cards.js (data) and public/locales/vi.cards.json (Vietnamese text).
// After generation the output files are the source of truth; re-run only if the master changes.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const md = fs.readFileSync(path.join(root, 'GAME_RULES_AND_ASSETS_MASTER.md'), 'utf8');

const cards = [], twists = [], vi = { cards: {}, twists: {}, tracks: {} };
for (const line of md.split('\n')) {
  if (!line.startsWith('| **')) continue;
  const c = line.split('|').slice(1, -1).map(s => s.trim());
  const id = +c[0].replace(/\*/g, '');
  const code = c[2].replace(/`/g, '');
  const m = c[3].match(/\*\*(.+?) \((.+)\)\*\*/);
  if (!m) continue;
  if (code.startsWith('T-')) {
    twists.push({ code, id });
    vi.twists[code] = { name: m[1], desc: c[4] };
  } else if (/^[RE]-/.test(code)) {
    cards.push({ code, id, set: code[0] === 'R' ? 'base' : 'exp', en: m[2], img: c[7].replace(/`/g, '') });
    vi.cards[code] = { name: m[1], cat: c[4], desc: c[6] };
  }
}
vi.tracks = {
  plains: { name: 'Thảo Nguyên Ngọc', desc: 'Đường đua cơ bản, góc cua rộng và ít bẫy.' },
  wildwood: { name: 'Rừng Rậm Hoang Dã', desc: 'Nhiều bẫy ngã và ô mũi tên bất ngờ.' },
  spiral: { name: 'Vòng Xoáy Hắc Diệp', desc: 'Xoắn ốc với nhiều đoạn thắt cổ chai.' },
  vortex: { name: 'Xoắn Ốc Không Gian', desc: 'Chặng chung kết với địa hình phức tạp.' },
};
if (cards.length !== 72 || twists.length !== 13) throw new Error(`parsed ${cards.length} cards, ${twists.length} twists`);

const js = `// GENERATED by tools/gen-cards.mjs from the master spec. Safe to hand-edit afterwards.
export const CARDS = ${JSON.stringify(cards.map(({ en, ...r }) => r), null, 0).replace(/\},/g, '},\n')};
export const TWISTS = ${JSON.stringify(twists)};
export const CARD = Object.fromEntries(CARDS.map(c => [c.code, c]));
export const SHEETS = {
  base: { file: 'cards/765fa4bba7c0.jpg', cols: 9, rows: 4 },
  exp: { file: 'cards/34c4ebe58b94.jpg', cols: 10, rows: 4 },
  twist: { file: 'cards/9ebfa55272d8.jpg', cols: 7, rows: 2 },
};
// Sprite cell of a card/twist on its sheet.
export function cell(id) {
  if (id >= 300 && id < 400) return { sheet: 'twist', col: (id - 300) % 7, row: Math.floor((id - 300) / 7) };
  const s = id >= 500 ? 'exp' : 'base', n = SHEETS[s].cols, k = id % 100;
  return { sheet: s, col: k % n, row: Math.floor(k / n) };
}
`;
fs.mkdirSync(path.join(root, 'shared'), { recursive: true });
fs.mkdirSync(path.join(root, 'public/locales'), { recursive: true });
fs.writeFileSync(path.join(root, 'shared/cards.js'), js);
fs.writeFileSync(path.join(root, 'public/locales/vi.cards.json'), JSON.stringify(vi, null, 1));
// English names, for hand-writing en.cards.json
console.log(cards.map(c => `${c.code}\t${c.en}`).join('\n'));
console.log(twists.map(t => t.code).join(' '));
